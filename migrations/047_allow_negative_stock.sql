-- 047. 마이너스 재고 허용 — item_lots.quantity >= 0 CHECK 제거
-- =====================================================
-- 로컬: 로컬 PostgreSQL / 실서버: Cloud SQL(서울)에서 실행. 재실행 안전.
--
-- 왜
--   현장에서는 "재고에 없는데 실제로는 나간" 일이 생긴다(입고 등록 누락 등).
--   이때 출고를 막거나 별도 기록으로 빼두면 현장이 멈추고, 장부와 실물이 어긋난다.
--   → 재고가 부족하면 그냥 마이너스로 내려가게 두고, 나중에 입고로 메운다.
--
-- 무엇이 바뀌나 (lib/stock.ts deductStock)
--   045 때: 있는 만큼만 빼고 부족분은 lot_id 없는 'shortage' 행으로 따로 기록(재고 미반영).
--   지금  : 부족분도 로트에 그대로 빼서 수량이 음수가 된다. shortage 개념 자체를 없앴다.
--           → 재고 합계 = 로트 합계 하나로 끝. "재고에 반영 안 된 기록"이라는 예외가 사라진다.
--
--   음수를 붙일 로트 = 차감 순서상 마지막으로 쓰던 로트.
--   입고 이력이 아예 없는 품목이면 소비기한 없는 오늘자 로트를 만들어 거기에 남긴다.
-- =====================================================

ALTER TABLE item_lots
  DROP CONSTRAINT IF EXISTS item_lots_quantity_check;

